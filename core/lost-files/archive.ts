export function findLostFile(id: string): LostFile | null {
  for (const folder of LOST_FOLDERS) {
    const found = folder.files.find((entry) => entry.id === id);
    if (found) return found;
  }
  return null;
}

export const LOST_FILE_COUNT = LOST_FOLDERS.reduce(
  (total, folder) => total + folder.files.length,
  0,
);
