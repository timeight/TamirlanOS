export type LostFileKind =
  | "txt"
  | "doc"
  | "jpg"
  | "png"
  | "psd"
  | "blend"
  | "unity"
  | "zip"
  | "pdf"
  | "readme";

/** Palette for the partially recovered preview drawn in the viewer. */
export type RecoveryTint = "warm" | "cool" | "mono" | "green";

export interface LostFile {
  id: string;
  name: string;
  kind: LostFileKind;
  size: string;
  modified: string;
  /** One line explaining why the file was kept. */
  note: string;
  body: readonly string[];
  /** Present on visual formats: the viewer reconstructs a lossy thumbnail. */
  recovery?: { seed: number; tint: RecoveryTint };
}

export interface LostFolder {
  id: string;
  name: string;
  caption: string;
  files: readonly LostFile[];
}

